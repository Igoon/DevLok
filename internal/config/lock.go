package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"devlok/internal/devlokerr"
	"gopkg.in/yaml.v3"
)

type Lock struct {
	Schema      int                      `yaml:"schema" json:"schema"`
	GeneratedAt time.Time                `yaml:"generated_at" json:"generated_at"`
	Platform    string                   `yaml:"platform" json:"platform"`
	Name        string                   `yaml:"name" json:"name"`
	Domain      string                   `yaml:"domain,omitempty" json:"domain,omitempty"`
	Web         LockedWeb                `yaml:"web" json:"web"`
	Runtime     map[string]LockedRuntime `yaml:"runtime,omitempty" json:"runtime,omitempty"`
	Services    map[string]LockedRuntime `yaml:"services,omitempty" json:"services,omitempty"`
}

type LockedRuntime struct {
	Version string `yaml:"version" json:"version"`
	SHA256  string `yaml:"sha256" json:"sha256"`
	URL     string `yaml:"url" json:"url"`
}

type LockedWeb struct {
	Server    string `yaml:"server" json:"server"`
	Version   string `yaml:"version" json:"version"`
	SHA256    string `yaml:"sha256" json:"sha256"`
	URL       string `yaml:"url" json:"url"`
	HTTPPort  int    `yaml:"http_port" json:"http_port"`
	HTTPSPort int    `yaml:"https_port" json:"https_port"`
}

const LockSchemaVersion = 1

func LoadLock(path string) (*Lock, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, err
		}
		return nil, devlokerr.Wrap(devlokerr.CodeInvalidManifest, err, "Lockfile tidak dapat dibaca.", "")
	}
	if len(data) > MaxSize {
		return nil, devlokerr.New(devlokerr.CodeInvalidManifest, "Lockfile terlalu besar.", "")
	}
	var l Lock
	if err := yaml.Unmarshal(data, &l); err != nil {
		return nil, devlokerr.Wrap(devlokerr.CodeInvalidManifest, err, "Lockfile tidak valid.", "Jalankan dl lock untuk membuat ulang.")
	}
	if l.Schema != LockSchemaVersion {
		return nil, devlokerr.New(devlokerr.CodeInvalidManifest, "Schema lockfile tidak didukung.", "Jalankan dl lock untuk membuat ulang.")
	}
	return &l, nil
}

func SaveLock(path string, l *Lock) error {
	data, err := yaml.Marshal(l)
	if err != nil {
		return devlokerr.Wrap(devlokerr.CodeInternal, err, "Lockfile tidak dapat diserialisasi.", "")
	}
	content := "# Generated by dl lock. Jangan edit manual.\n" + string(data)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return devlokerr.Wrap(devlokerr.CodePermissionDenied, err, "Folder lockfile tidak dapat dibuat.", "")
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return devlokerr.Wrap(devlokerr.CodePermissionDenied, err, "Lockfile tidak dapat ditulis.", "")
	}
	_ = os.Remove(path)
	if err := os.Rename(tmp, path); err != nil {
		return devlokerr.Wrap(devlokerr.CodePermissionDenied, err, "Lockfile tidak dapat diselesaikan.", "")
	}
	return nil
}

func CompareLock(m *Manifest, l *Lock) []string {
	if l == nil {
		return nil
	}
	var warnings []string
	if l.Name != m.Name {
		warnings = append(warnings, fmt.Sprintf("Nama manifest %q berbeda dengan lock %q.", m.Name, l.Name))
	}
	if l.Domain != "" && l.Domain != m.BaseDomain() {
		warnings = append(warnings, fmt.Sprintf("Domain manifest %q berbeda dengan lock %q.", m.BaseDomain(), l.Domain))
	}
	if got := l.Runtime["php"]; got.Version != "" && !lockMatches(got.Version, m.Web.PHP) {
		warnings = append(warnings, fmt.Sprintf("PHP manifest %s berbeda dengan lock %s.", m.Web.PHP, got.Version))
	}
	if got := l.Runtime["node"]; got.Version != "" {
		if want, ok := m.Runtime["node"]; ok && !lockMatches(got.Version, want) {
			warnings = append(warnings, fmt.Sprintf("Node manifest %s berbeda dengan lock %s.", want, got.Version))
		}
	}
	if got := l.Services["mysql"]; got.Version != "" {
		want := m.Services["mysql"]
		if want == "" {
			want = "8.4"
		}
		if !lockMatches(got.Version, want) {
			warnings = append(warnings, fmt.Sprintf("MySQL manifest %s berbeda dengan lock %s.", want, got.Version))
		}
	}
	return warnings
}

func lockMatches(version, constraint string) bool {
	if constraint == "" || constraint == "latest" {
		return true
	}
	return version == constraint || strings.HasPrefix(version, constraint+".")
}

func LockedVersion(l *Lock, section, name string) string {
	if l == nil {
		return ""
	}
	switch section {
	case "runtime":
		return l.Runtime[name].Version
	case "services":
		return l.Services[name].Version
	case "web":
		return l.Web.Version
	}
	return ""
}
